#!/usr/bin/env node
/**
 * Local Postgres bootstrap: compose up → roles/DBs → env files → migrate both.
 * Safe to re-run. Does not overwrite existing .env files.
 */
import { execFileSync, spawnSync } from "node:child_process"
import { randomBytes } from "node:crypto"
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const serverDir = join(root, "apps/server")
const landlordDir = join(root, "apps/landlord-web")
const residentDir = join(root, "apps/resident-web")

const OWNER_USER = "chum"
const OWNER_PASSWORD = "chum_local_dev"
const APP_USER = "villuh_app"
const APP_PASSWORD = "villuh_app_password_changeme"
const OWNER_URL = `postgres://${OWNER_USER}:${OWNER_PASSWORD}@localhost:5432/villuh`
const APP_URL = `postgres://${APP_USER}:${APP_PASSWORD}@localhost:5432/villuh`
const OWNER_TEST_URL = `postgres://${OWNER_USER}:${OWNER_PASSWORD}@localhost:5432/villuh_test`
const APP_TEST_URL = `postgres://${APP_USER}:${APP_PASSWORD}@localhost:5432/villuh_test`

function log(msg) {
  console.log(`\n▸ ${msg}`)
}

const isWin = process.platform === "win32"

function run(cmd, args, opts = {}) {
  const result = spawnSync(cmd, args, {
    cwd: root,
    stdio: "inherit",
    shell: isWin && cmd === "pnpm",
    ...opts,
  })
  if (result.status !== 0) {
    throw new Error(`Command failed (${result.status}): ${cmd} ${args.join(" ")}`)
  }
}

function docker(args, spawnOpts = {}) {
  const result = spawnSync("docker", args, {
    cwd: root,
    encoding: "utf8",
    ...spawnOpts,
  })
  if (result.status !== 0) {
    const err = (result.stderr || result.stdout || "").trim()
    throw new Error(`docker ${args.join(" ")} failed:\n${err}`)
  }
  return result
}

function dockerCompose(args, spawnOpts = {}) {
  return docker(["compose", ...args], spawnOpts)
}

function psql(database, sql) {
  const result = dockerCompose(
    [
      "exec",
      "-T",
      "postgres",
      "psql",
      "-v",
      "ON_ERROR_STOP=1",
      "-U",
      OWNER_USER,
      "-d",
      database,
      "-c",
      sql,
    ],
    { stdio: ["ignore", "pipe", "pipe"] }
  )
  if (result.stdout?.trim()) process.stdout.write(result.stdout)
}

function psqlFile(database, filePath) {
  const sql = readFileSync(filePath, "utf8")
  const result = dockerCompose(
    [
      "exec",
      "-T",
      "postgres",
      "psql",
      "-v",
      "ON_ERROR_STOP=1",
      "-U",
      OWNER_USER,
      "-d",
      database,
    ],
    { input: sql, stdio: ["pipe", "pipe", "pipe"] }
  )
  if (result.stdout?.trim()) process.stdout.write(result.stdout)
}

function writeEnvIfMissing(path, contents) {
  if (existsSync(path)) {
    console.log(`  keep ${path} (already exists)`)
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, contents, "utf8")
  console.log(`  wrote ${path}`)
}

function existingSecret() {
  const serverEnv = join(serverDir, ".env")
  if (!existsSync(serverEnv)) return null
  const match = readFileSync(serverEnv, "utf8").match(/^BETTER_AUTH_SECRET=(.+)$/m)
  const value = match?.[1]?.trim()
  return value && !value.startsWith("#") ? value : null
}

function serverEnv(secret) {
  return `# Local Docker Postgres — generated by scripts/setup-local-db.mjs
PORT=4000
BETTER_AUTH_URL=http://localhost:4000
BETTER_AUTH_SECRET=${secret}
CORS_ALLOWED_ORIGINS=http://localhost:3000,http://localhost:3001

GOOGLE_CLIENT_ID=google_client_id_local
GOOGLE_CLIENT_SECRET=google_client_secret_local

RESEND_API_KEY=re_local_placeholder
RESEND_FROM_EMAIL=onboarding@resend.dev

STRIPE_SECRET_KEY=sk_test_placeholder_local
STRIPE_WEBHOOK_SECRET=whsec_placeholder_local
STRIPE_STARTER_PRICE_ID=price_starter_local
STRIPE_GROWTH_PRICE_ID=price_growth_local
STRIPE_PRO_PRICE_ID=price_pro_local
STRIPE_CLIENT_ID=ca_local_placeholder

NEXT_PUBLIC_APP_URL=http://localhost:3000
NEXT_PUBLIC_API_URL=http://localhost:4000

DATABASE_URL=${OWNER_URL}
DATABASE_APP_URL=${APP_URL}
DATABASE_OWNER_TEST_URL=${OWNER_TEST_URL}
DATABASE_TEST_URL=${APP_TEST_URL}

S3_BUCKET=villuh-local-bucket
AWS_REGION=us-east-1
AWS_ACCESS_KEY_ID=local
AWS_SECRET_ACCESS_KEY=local
`
}

function webEnv({ secret, appUrl }) {
  return `# Local — generated by scripts/setup-local-db.mjs
# BETTER_AUTH_SECRET must match apps/server/.env
DATABASE_APP_URL=${APP_URL}
BETTER_AUTH_SECRET=${secret}
BETTER_AUTH_URL=http://localhost:4000

NEXT_PUBLIC_API_URL=http://localhost:4000
API_INTERNAL_URL=http://localhost:4000
NEXT_PUBLIC_APP_URL=${appUrl}
NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY=pk_test_placeholder_local
NEXT_PUBLIC_STRIPE_CLIENT_ID=ca_local_placeholder
`
}

log("Checking Docker")
try {
  execFileSync("docker", ["info"], { stdio: "pipe" })
} catch {
  console.error("Docker is not running. Start Docker Desktop and re-run: pnpm db:setup")
  process.exit(1)
}

log("Starting Postgres (docker compose)")
dockerCompose(["up", "-d", "--wait"], { stdio: "inherit" })

log("Bootstrapping roles and databases")
psqlFile("villuh", join(serverDir, "scripts/bootstrap-roles.sql"))
psqlFile("villuh", join(serverDir, "scripts/bootstrap-grants.sql"))
psqlFile("villuh_test", join(serverDir, "scripts/bootstrap-grants.sql"))

log("Writing env files (skip if present)")
const secret = existingSecret() ?? randomBytes(32).toString("hex")
writeEnvIfMissing(join(serverDir, ".env"), serverEnv(secret))
writeEnvIfMissing(join(landlordDir, ".env.local"), webEnv({ secret, appUrl: "http://localhost:3000" }))
writeEnvIfMissing(join(residentDir, ".env.local"), webEnv({ secret, appUrl: "http://localhost:3001" }))

log("Migrating villuh")
run("pnpm", ["--filter", "@villuh/server", "migrate"], { env: process.env })

log("Migrating villuh_test")
run("pnpm", ["--filter", "@villuh/server", "migrate"], {
  env: { ...process.env, DATABASE_URL: OWNER_TEST_URL },
})

log("Re-granting villuh_app after migrations")
psqlFile("villuh", join(serverDir, "scripts/bootstrap-grants.sql"))
psqlFile("villuh_test", join(serverDir, "scripts/bootstrap-grants.sql"))

log("Verifying")
psql("villuh", "SELECT rolname FROM pg_roles WHERE rolname = 'villuh_app';")
psql("villuh", "SELECT slug, name, stripe_price_id FROM billing_plans ORDER BY sort_order;")
psql(
  "villuh",
  "SELECT datname FROM pg_database WHERE datname IN ('villuh', 'villuh_test') ORDER BY 1;"
)

console.log(`
Done.

  Dev DB     ${OWNER_URL}
  App role   ${APP_URL}
  Test DB    ${OWNER_TEST_URL}

  pnpm dev          landlord :3000 · resident :3001 · API :4000
  pnpm test         uses villuh_test

Sign up in the landlord app to create the first org (permissions seed on org create).
Unit statuses seed the first time you open Units.
`)
